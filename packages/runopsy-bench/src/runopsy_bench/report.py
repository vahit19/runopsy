"""Rendering the benchmark as a document that can be committed and diffed.

Deliberately contains no timestamp. A report stamped with the moment it ran changes on
every invocation, so a reviewer cannot tell a real movement in the numbers from a
re-run. Without one, ``git diff`` on this file shows exactly what changed about the
engine and nothing else.
"""

from __future__ import annotations

from runopsy_bench.metrics import BenchmarkReport
from runopsy_core import __version__ as core_version
from runopsy_core.schema import SCHEMA_VERSION


def _percent(value: float) -> str:
    return f"{value * 100:.1f}%"


def comparison_markdown(reports: tuple[BenchmarkReport, ...]) -> str:
    """A Markdown report comparing strategies over the same labelled cases."""
    if not reports:
        return "# Runopsy benchmark\n\nNo strategies were scored.\n"

    reference = reports[-1]
    lines: list[str] = [
        "# Runopsy benchmark — onset localization",
        "",
        "Generated by `runopsy bench --write`. Reproducible offline: the cases are",
        "generated rather than sampled, and every strategy below is deterministic and",
        "spends no tokens.",
        "",
        f"- engine version: `{core_version}`",
        f"- trace schema: `{SCHEMA_VERSION}`",
        f"- cases: {len(reference.results)} "
        f"({len(reference.scored)} scored, {len(reference.healthy)} healthy control, "
        f"{len(reference.blind_spots)} labelled blind spot)",
        "",
        "## Results",
        "",
        "| strategy | top-1 | top-3 | mean step distance | false positives |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]

    for report in reports:
        lines.append(
            f"| `{report.strategy_name}` | {_percent(report.top1_accuracy)} "
            f"| {_percent(report.top3_recall)} | {report.mean_step_distance:.2f} "
            f"| {_percent(report.false_positive_rate)} |"
        )

    lines += [
        "",
        "## How to read this",
        "",
        "`no_diagnosis` scores zero by construction. It is the floor: a percentage means",
        "little without knowing what doing nothing earns.",
        "",
        "`last_failure` is the baseline that matters. Scrolling to the bottom of a log and",
        "blaming the last thing that broke is free and instant, so an engine that does not",
        "clearly beat it has no reason to exist. Where it fails is precisely where it is",
        "expensive to fail: the last failure is usually a symptom of something that went",
        "wrong much earlier.",
        "",
        "`first_failure` shows how much of the score comes from the bare intuition that",
        "earlier is better, rather than from the ranking built on top of it.",
        "",
        "The false positive column is not a tuning parameter. Spurious findings are what",
        "get a diagnosis tool switched off, so anything above zero is a defect.",
        "",
        "## What is excluded, and why",
        "",
        "Cases whose onset leaves nothing anomalous in the trace are labelled blind spots",
        "and left out of the accuracy figure. Scoring them would measure luck; dropping",
        "them silently would inflate the headline and hide the coverage gap that semantic",
        "analysis exists to close.",
        "",
    ]

    if reference.blind_spots:
        lines.append("| blind spot | why structural analysis cannot reach it |")
        lines.append("| --- | --- |")
        for result in reference.blind_spots:
            lines.append(f"| `{result.case.name}` | {result.case.description} |")
        lines.append("")

    misses = reference.failures()
    lines += ["## Cases the engine still misses", ""]
    if not misses:
        lines.append("None.")
    else:
        lines.append("| case | true onset | ranked | in top 3 |")
        lines.append("| --- | ---: | --- | :---: |")
        for result in misses:
            ranked = ", ".join(str(step) for step in result.predicted_steps[:3]) or "—"
            lines.append(
                f"| `{result.case.name}` | {result.case.onset_step} | {ranked} "
                f"| {'yes' if result.in_top_k else 'no'} |"
            )
    lines.append("")

    lines += [
        "## Scope",
        "",
        "These are synthetic single-fault traces with declared ground truth. They",
        "establish that the ranking behaves as designed; they do not establish that it",
        "helps on real work. That requires the fault-injection and opt-in layers of",
        "Runopsy-Bench, and a measured reduction in time-to-diagnosis on a real workload.",
        "No claim beyond the table above is supported yet.",
        "",
    ]

    return "\n".join(lines)
